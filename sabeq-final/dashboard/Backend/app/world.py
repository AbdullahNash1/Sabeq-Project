"""The final simulation world (docs/WORLD.md), loaded from the two shared files.

Route names, waypoints, incident, start, First Aid Center and scan yaws come ONLY from
world_meta.json (generated by docs/team/gen_world.py) and routes.yaml (read by Node 2).
At startup the two are checked against each other exactly like tools/check_routes.py;
any mismatch raises WorldConfigError.

All geometry here is Gazebo world ENU metres (x = east, y = north). Pure Python: no
FastAPI, no ROS. The path helpers are ports of docs/team/demo_common.py (that file is
read-only for us, so it is copied, not imported).
"""
import json
import math
from dataclasses import dataclass
from pathlib import Path

import yaml

from app.config import Settings

TOL = 1e-6

# World facts that are constants in the team scripts, not fields of world_meta.json.
CART_STOP_BEFORE_M = 5.0  # demo_common.CART_STOP_BEFORE: cart stops this far before the incident
SCAN_ZONE_END_M = 36.0  # gen_world.CROWD_RANGE[1]: people up to here are visible from the hover point

Point = tuple  # (e, n)


class WorldConfigError(Exception):
    """world_meta.json and routes.yaml are missing, unreadable or disagree."""


# --- ENU polyline helpers (demo_common.py ports) ---------------------------------


def path_length(path) -> float:
    return sum(math.dist(a, b) for a, b in zip(path, path[1:]))


def along(path, s: float) -> tuple:
    """(e, n, heading_enu_rad) at distance s along the path, clamped to its ends."""
    s = max(0.0, s)
    x1, y1, h = path[0][0], path[0][1], 0.0
    for (x0, y0), (x1, y1) in zip(path, path[1:]):
        seg = math.hypot(x1 - x0, y1 - y0)
        if seg < TOL:
            continue
        h = math.atan2(y1 - y0, x1 - x0)
        if s <= seg:
            t = s / seg
            return x0 + t * (x1 - x0), y0 + t * (y1 - y0), h
        s -= seg
    return x1, y1, h


def project(path, p) -> tuple:
    """(distance along the path, distance from it) of the path point closest to p."""
    best, best_s, walked = math.inf, 0.0, 0.0
    for a, b in zip(path, path[1:]):
        seg = math.dist(a, b)
        t = 0.0
        if seg > TOL:
            t = max(0.0, min(1.0, ((p[0] - a[0]) * (b[0] - a[0]) + (p[1] - a[1]) * (b[1] - a[1])) / seg ** 2))
        d = math.dist(p, (a[0] + t * (b[0] - a[0]), a[1] + t * (b[1] - a[1])))
        if d < best:
            best, best_s = d, walked + t * seg
        walked += seg
    return best_s, best


def dedup(points) -> list:
    out = []
    for p in points:
        p = (float(p[0]), float(p[1]))
        if not out or math.dist(p, out[-1]) > TOL:
            out.append(p)
    return out


def compass_deg(heading_enu_rad: float) -> float:
    """ENU yaw (counter-clockwise from east) -> compass bearing = PX4 NED yaw."""
    return round((90.0 - math.degrees(heading_enu_rad)) % 360.0, 3) % 360.0  # 359.9998 (yaw 1.5708) -> 0


def angle_diff_deg(a: float, b: float) -> float:
    return abs((a - b + 180.0) % 360.0 - 180.0)


# --- the world ---------------------------------------------------------------------


@dataclass(frozen=True)
class WorldRoute:
    id: str
    label: dict  # {"en": ..., "ar": ...} from ROUTE_LABELS
    path: list  # routes.yaml waypoints = cart start -> route -> incident
    length_m: float
    scan_yaw_ned_deg: float
    scan_people: int  # people in the scan zone (what YOLO can see from the hover point)


@dataclass(frozen=True)
class World:
    name: str
    start: Point  # cart start (start plaza)
    start_heading_rad: float
    incident: Point
    patient: tuple  # (e, n, yaw_enu_rad): the injured visitor lying at the incident
    home: Point  # PX4 NED origin in ENU (drone spawn)
    hover_point: Point
    first_aid_door: Point
    first_aid_stop: Point  # where the returning cart stops, beside the door
    first_aid_route: list
    routes: dict  # id -> WorldRoute, in scan order

    @property
    def route_ids(self) -> list:
        return list(self.routes)

    def cart_path(self, route_id: str) -> list:
        return list(self.routes[route_id].path)

    def return_path(self, route_id: str) -> list:
        """demo_common.build_return_path: from where the cart stopped (5 m before the incident),
        back along the route to the start, then to the First Aid Center stop."""
        rev = self.routes[route_id].path[::-1]
        x, y, _ = along(rev, CART_STOP_BEFORE_M)
        out, walked = [(x, y)], 0.0
        for a, b in zip(rev, rev[1:]):
            walked += math.dist(a, b)
            if walked > CART_STOP_BEFORE_M + TOL and b != out[-1]:
                out.append(b)
        out += [p for p in self.first_aid_route if p != out[-1]]
        return out

    def route_facing(self, heading_deg: float, tolerance_deg: float) -> "str | None":
        """The route whose scan yaw the drone faces within the tolerance, if any."""
        for rid, r in self.routes.items():
            if angle_diff_deg(heading_deg, r.scan_yaw_ned_deg) <= tolerance_deg:
                return rid
        return None


def _read(path: Path, what: str, parse):
    try:
        return parse(path.read_text())
    except FileNotFoundError:
        raise WorldConfigError(f"{what} not found: {path}") from None
    except (OSError, ValueError, yaml.YAMLError) as exc:
        raise WorldConfigError(f"{what} could not be read ({path}): {exc}") from None


def check_routes(config: dict, meta: dict) -> list:
    """Mismatches between routes.yaml and world_meta.json (same rules as tools/check_routes.py)."""
    errors = []
    names = list(meta.get("routes") or {})
    routes = config.get("routes") or {}
    if list(routes) != names:
        errors.append(f"routes.yaml route names {list(routes)} != world_meta.json routes {names}")
    if config.get("scan_order") != names:
        errors.append(f"routes.yaml scan_order {config.get('scan_order')} != world_meta.json routes {names}")
    start = meta["cart_start_enu"][:2]
    if not _same([config.get("start")], [start]):
        errors.append(f"routes.yaml start {config.get('start')} != cart_start_enu {start}")
    if not _same([config.get("incident")], [meta["incident_enu"]]):
        errors.append(f"routes.yaml incident {config.get('incident')} != incident_enu {meta['incident_enu']}")
    for name in names:
        want = dedup([start] + meta["routes"][name]["waypoints_enu"] + [meta["incident_enu"]])
        got = [tuple(p) for p in ((routes.get(name) or {}).get("waypoints") or [])]
        if not _same(got, want):
            errors.append(f"{name}: routes.yaml waypoints {got} != world_meta.json path {want}")
    return errors


def _same(a, b) -> bool:
    try:
        return len(a) == len(b) and all(math.dist(p, q) <= TOL for p, q in zip(a, b))
    except (TypeError, ValueError):
        return False


def _scan_people(meta: dict, route: str) -> int:
    return sum(int(p.get("size", 1)) for p in meta.get("people", [])
               if p.get("route") == route and p.get("s") is not None and p["s"] <= SCAN_ZONE_END_M + TOL)


def load_world(settings: Settings) -> World:
    meta_path = settings.resolve_path(settings.world_meta)
    routes_path = settings.resolve_path(settings.routes_yaml)
    meta = _read(meta_path, "WORLD_META", json.loads)
    config = _read(routes_path, "ROUTES_YAML", yaml.safe_load) or {}

    try:
        errors = check_routes(config, meta)
    except (KeyError, TypeError) as exc:
        raise WorldConfigError(f"{meta_path} is missing a required field: {exc}") from None
    missing = [r for r in meta["routes"] if r not in settings.route_labels]
    if missing:
        errors.append(f"ROUTE_LABELS has no label for {missing}")
    for rid, label in settings.route_labels.items():
        if rid in meta["routes"] and not any(isinstance(label.get(k), str) and label[k] for k in ("en", "ar")):
            errors.append(f"ROUTE_LABELS[{rid!r}] must be {{\"en\": ..., \"ar\": ...}} with at least one text")
    best = settings.mock_best_route
    if best is not None and best not in meta["routes"]:
        errors.append(f"MOCK_BEST_ROUTE={best!r} is not one of {list(meta['routes'])}")
    if errors:
        raise WorldConfigError(
            f"routes.yaml ({routes_path}) does not match world_meta.json ({meta_path}):\n  - "
            + "\n  - ".join(errors)
            + "\nRun tools/check_routes.py and fix routes.yaml (never the teammates' files)."
        )

    fa = meta.get("first_aid") or {}
    routes = {}
    for rid, r in meta["routes"].items():
        path = dedup(config["routes"][rid]["waypoints"])
        routes[rid] = WorldRoute(
            id=rid, label=dict(settings.route_labels[rid]), path=path, length_m=path_length(path),
            scan_yaw_ned_deg=float(r["scan_yaw_ned_deg"]), scan_people=_scan_people(meta, rid),
        )
    start = (float(meta["cart_start_enu"][0]), float(meta["cart_start_enu"][1]))
    door = tuple(map(float, fa.get("door_enu", start)))
    fa_route = dedup(fa.get("cart_route_enu") or [start])
    return World(
        name=meta.get("world", ""),
        start=start,
        start_heading_rad=float(meta["cart_start_enu"][2]),
        incident=tuple(map(float, meta["incident_enu"])),
        patient=tuple(map(float, meta.get("patient_enu") or [*meta["incident_enu"], 0.0])),
        home=tuple(map(float, meta.get("home_enu", start))),
        hover_point=tuple(map(float, meta.get("hover_point_enu", start))),
        first_aid_door=door,
        first_aid_stop=fa_route[-1],
        first_aid_route=fa_route,
        routes=routes,
    )
